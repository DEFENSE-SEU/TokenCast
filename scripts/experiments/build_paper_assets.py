def to_latex(caption: str) -> str:

    text = re.sub(r"\*\*(.+?)\*\*", lambda m: r"\textbf{" + m.group(1) + "}", caption)
    text = re.sub(r"`([^`]+)`", lambda m: r"\texttt{" + m.group(1).replace("_", r"\_") + "}", text)
    text = re.sub(r"(?<!\\)%", r"\\%", text)
    text = re.sub(r"(\d)x\b", r"\1$\\times$", text)
    return text


def figure_floats(captions: Path, keep: str = "") -> list[str]:
    blocks = {}
    current = None
    for line in captions.read_text(encoding="utf-8").split("\n"):
        heading = re.match(r"^## (\S+)", line)
        if heading:
            current = heading.group(1)
            continue
        if current and line.startswith("**"):
            blocks[current] = line.strip()
            current = None
    lines = [r"% Generated by scripts.experiments.build_paper_assets -- do not edit by hand.", ""]
    for name, label, placement, wide in FLOATS:
        if keep and not name.startswith(keep):
            continue
        caption = blocks.get(name)
        if not caption:
            print(f"skipped {name}: no caption", flush=True)
            continue
        star = "*" if wide else ""
        width = r"\linewidth" if wide else r"\linewidth"
        lines += [
            r"\begin{figure" + star + "}[" + placement + "]",
            r"\centering",
            r"\includegraphics[width=" + width + r"]{figures/" + name + ".pdf}",
            r"\caption{" + to_latex(caption) + "}",
            r"\label{" + label + "}",
            r"\end{figure" + star + "}",
            "",
        ]
        print(f"wrote float for {name}", flush=True)
    return lines


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    repo = Path(__file__).resolve().parents[2]
    parser.add_argument("--output", type=Path, default=repo / "docs" / "paper")
    parser.add_argument("--captions", type=Path, default=repo / "docs" / "figures" / "captions.md")
    parser.add_argument("--cohort", default="mt-v18")
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)

    tables = main_table(args.cohort) + interval_table(args.cohort)
    (args.output / "tables.tex").write_text("\n".join(tables) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {args.output / 'tables.tex'} ({len(tables)} lines)", flush=True)

    for target, keep in (("figures.tex", "f"), ("figures_appendix.tex", "a")):
        floats = figure_floats(args.captions, keep)
        (args.output / target).write_text("\n".join(floats) + "\n", encoding="utf-8", newline="\n")
        print(f"wrote {args.output / target} ({len(floats)} lines)", flush=True)


if __name__ == "__main__":
    main()
