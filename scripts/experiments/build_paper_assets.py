def escape(text: str) -> str:
    return text.replace("_", r"\_").replace("%", r"\%").replace("&", r"\&")


def label_of(candidate: str) -> str:
    if candidate in PRETTY:
        return PRETTY[candidate]
    return r"\texttt{" + escape(candidate) + "}"


def fmt(value: float) -> str:
    if value >= 1e5:
        return f"{value / 1e3:,.0f}k"
    if value >= 1e3:
        return f"{value:,.0f}"
    if value >= 10:
        return f"{value:.1f}"
    return f"{value:.2f}"


def main_table(cohort: str) -> list[str]:
    rows, ours = read_table(RUNS / cohort / "table" / "summary.md")
    present = [p for p in POSITIONS if p in rows]


    every = sorted({c for p in present for c in rows[p] if ":" not in c})
    best = {p: min((c for c in rows[p] if ":" not in c),
                   key=lambda c: number(rows[p][c][1])) for p in present}

    grouped: dict[str, list[str]] = {f: [] for f in FAMILY_ORDER}
    for candidate in every:
        family = "ours" if candidate in ours.values() else family_of(candidate)
        grouped.setdefault(family, []).append(candidate)
    for family in grouped:
        grouped[family].sort(key=lambda c: min(
            (number(rows[p][c][1]) / number(rows[p][best[p]][1]) for p in present if c in rows[p]),
            default=99.0))

    lines = [
        r"% Generated by scripts.experiments.build_paper_assets -- do not edit by hand.",
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{\textbf{Mean absolute error at every prediction position, " + cohort.replace("mt-", "")
        + r".} Task-macro MAE over three split seeds and five folds, in each position's own unit; lower "
          r"is better and the best entry in a column is bold. A dash marks a position the method does not "
          r"support or was not scored at. Full per-arm statistics, including paired confidence intervals "
          r"and the interval columns, are in the appendix.}",
        r"\label{tab:main}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{l" + "r" * len(present) + "}",
        r"\toprule",
        "Method & " + " & ".join(HEADS[p] for p in present) + r" \\",
        " & " + " & ".join(f"({UNITS[p]})" for p in present) + r" \\",
        r"\midrule",
    ]
    for family in FAMILY_ORDER:
        if family == "ours":
            cells = []
            for position in present:
                value = fmt(number(rows[position][ours[position]][1]))
                cells.append(r"\textbf{" + value + "}" if ours[position] == best[position] else value)
            lines += [r"\midrule", r"TokenETC (ours) & " + " & ".join(cells) + r" \\"]
            continue
        members = grouped.get(family) or []
        if not members:
            continue
        lines.append(r"\multicolumn{" + str(len(present) + 1) + r"}{l}{\textit{"
                     + FAMILY_TITLE[family] + r"}} \\")
        for candidate in members:
            cells = []
            for position in present:
                if candidate not in rows[position]:
                    cells.append("--")
                    continue
                value = fmt(number(rows[position][candidate][1]))
                cells.append(r"\textbf{" + value + "}" if candidate == best[position] else value)
            lines.append(label_of(candidate) + " & " + " & ".join(cells) + r" \\")
        lines.append(r"\addlinespace[2pt]")
    lines.append(r"\bottomrule")
    lines += [r"\end{tabular}", r"\end{table}", ""]
    return lines


def interval_table(cohort: str) -> list[str]:
    rows, ours = read_table(RUNS / cohort / "table" / "summary.md")
    present = [p for p in POSITIONS if p in rows]
    wanted: list[str] = []
    for position in present:
        mine = ours[position]
        rival = min((c for c in rows[position] if c != mine and family_of(c) != "ours"),
                    key=lambda c: number(rows[position][c][1]))
        for candidate in (mine, rival, "empirical"):
            if candidate in rows[position] and candidate not in wanted:
                wanted.append(candidate)
    lines = [
        r"\begin{table}[t]",
        r"\centering",
        r"\caption{\textbf{Interval quality at the nominal 90\% level, " + cohort.replace("mt-", "")
        + r".} Realized coverage, normalized width $(u-l)/\max(|y|,1)$ and mean interval score, "
          r"task-macro over three split seeds. Coverage closest to 0.90 and the lowest interval score "
          r"are the targets; a narrow interval that under-covers is not an improvement.}",
        r"\label{tab:interval}",
        r"\small",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{ll" + "rrr" + "}",
        r"\toprule",
        r"Position & Method & Coverage & Width & Interval score \\",
        r"\midrule",
    ]
    for position in present:
        first = True
        for candidate in wanted:
            if candidate not in rows[position]:
                continue
            cells = rows[position][candidate]
            head = HEADS[position] if first else ""
            first = False
            name = label_of(candidate)
            if candidate == ours[position]:
                name = r"\textbf{" + name + "}"
            lines.append(f"{head} & {name} & {number(cells[6]):.3f} & {fmt(number(cells[8]))} "
                         f"& {fmt(number(cells[7]))} " + r"\\")
        lines.append(r"\addlinespace[2pt]")
    lines[-1] = r"\bottomrule"
    lines += [r"\end{tabular}", r"\end{table}", ""]
    return lines


