def issue_text(statement: str) -> str:
    marker = "## Issue"
    return statement.split(marker, 1)[1].strip() if marker in statement else statement.strip()


def build(manifest_path: Path, *, model: str, reasoning_effort: str, manifest_out: Path) -> dict:
    source = json.loads(manifest_path.read_text(encoding="utf-8"))
    derived = copy.deepcopy(source)
    stem = manifest_out.stem.replace("development_gpt_oauth_", "swebench-gpt-oauth-").replace("_", "-")
    derived["manifest_id"] = stem
    derived["protocol_id"] = stem.replace("-v1", "-collection-v1")
    derived.pop("condition_digest", None)
    tasks = []
    for task in source["tasks"]:
        pack_dir = REPO / task["pack_path"]
        pack = json.loads((pack_dir / "pack.json").read_text(encoding="utf-8"))
        statement = (pack_dir / "task.md").read_text(encoding="utf-8")
        out_dir = pack_dir.parent / f"{pack_dir.name}_{SUFFIX}"
        out_dir.mkdir(exist_ok=True)
        new_pack = copy.deepcopy(pack)
        new_pack["task_pack_id"] = f"{pack['task_pack_id']}-{SUFFIX.replace('_', '-')}"
        new_pack["task_id"] = f"{task['task_id']}-{SUFFIX.replace('_', '-')}"
        new_pack["source"] = {**pack.get("source", {}), "estimation_of_task_id": task["task_id"], "protocol": "pre-execution-self-estimation-v1"}
        (out_dir / "pack.json").write_text(json.dumps(new_pack, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
        (out_dir / "task.md").write_text(SYSTEM_ROLE + "\n" + WORKED_EXAMPLE + "\n" + USER_INSTRUCTION.format(issue=issue_text(statement)), encoding="utf-8")
        derived_task = copy.deepcopy(task)
        derived_task["task_id"] = new_pack["task_id"]
        derived_task["pack_path"] = str(Path(task["pack_path"]).parent / out_dir.name).replace("\\", "/")
        derived_task["title"] = f"Self-estimation of {task['title']}"
        derived_task["requirements"] = ["estimate the Tokens a full run on the pinned seed workspace would consume, without fixing the issue"]
        tasks.append(derived_task)
    derived["tasks"] = tasks
    derived["schedule"]["task_order"] = [t["task_id"] for t in tasks]
    condition = copy.deepcopy(source["model_conditions"][0])
    condition_id = f"swebench-{model.replace('.', '-')}-{SUFFIX.replace('_', '-')}"
    condition.update({"condition_id": condition_id, "actor_model_id": model, "configured_model": model, "reasoning_effort": reasoning_effort})
    derived["model_conditions"] = [condition]
    derived["schedule"]["condition_order"] = [condition_id]
    manifest_out.write_text(json.dumps(derived, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
    return derived


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", type=Path, default=REPO / "configs" / "collection" / "development_gpt_oauth_v18.json")
    parser.add_argument("--model", default="gpt-5.5")
    parser.add_argument("--reasoning-effort", default="low")
    parser.add_argument("--manifest-out", type=Path, default=REPO / "configs" / "collection" / "development_gpt_oauth_self_estimate_v1.json")
    args = parser.parse_args()
    derived = build(args.manifest, model=args.model, reasoning_effort=args.reasoning_effort, manifest_out=args.manifest_out)
    print(f"{len(derived['tasks'])} estimation packs; manifest {args.manifest_out}; condition {derived['schedule']['condition_order']}")


if __name__ == "__main__":
    main()
